    public partial class ManagaeTutors : Form
    {
        private readonly string connectionString;
        private int selectedId;
        private string idColumn;
        private bool tutorIdAutoGenerated;
        private string activeColumn;
        private bool updatingSelection;

        public ManagaeTutors()
        {
            InitializeComponent();
            EduConnectInputGuidance.Attach(this);
            if (LicenseManager.UsageMode == LicenseUsageMode.Designtime) return;
            var cfg = ConfigurationManager.ConnectionStrings[
                "NextGen__7.Properties.Settings.Edu_ConnectConnectionString"];
            if (cfg == null) throw new InvalidOperationException("Missing database configuration.");
            connectionString = cfg.ConnectionString;
            gridTutors.SelectionChanged += (s, e) => ShowSelected();
            btnNew.Click += (s, e) => NewTutor();
            btnSave.Click += (s, e) => SaveTutor();
            btnRemoveTutor.Click += (s, e) => RemoveTutor();
            btnCancel.Click += (s, e) => ClearEditor();
            btnBack.Click += (s, e) => Close();
            btnRefresh.Click += (s, e) => LoadTutors();
            btnAssignCourse.Click += (s, e) => AssignCourse();
            btnAvailability.Click += (s, e) => OpenAvailability();
            btnCreateTutorLogin.Click += (s, e) => CreateTutorLogin();
            btnResetTutorLogin.Click += (s, e) => ResetTutorLogin();
            txtSearch.TextChanged += (s, e) => ApplySearch();
            Load += (s, e) => { LoadCourses(); LoadTutors(); };
        }

        private static string Column(DataTable table, string logicalName)
        {
            foreach (DataColumn column in table.Columns)
                if (column.ColumnName.Trim('\uFEFF', ' ').Equals(logicalName,
                    StringComparison.OrdinalIgnoreCase)) return column.ColumnName;
            return null;
        }

        private DataTable ReadTable(string tableName)
        {
            var table = new DataTable();
            using (var db = new OleDbConnection(connectionString))
            using (var adapter = new OleDbDataAdapter("SELECT * FROM [" + tableName + "]", db))
                adapter.Fill(table);
            return table;
        }

        private void LoadTutors()
        {
            try
            {
                var table = ReadTable("TUTOR");
                idColumn = Column(table, "TutorID");
                if (idColumn == null)
                    throw new InvalidOperationException("The TUTOR table has no TutorID column.");
                activeColumn = Column(table, "IsActive");
                // Detect whether the Access primary key is an AutoNumber field.
                using (var db = new OleDbConnection(connectionString))
                {
                    db.Open();
                    using (var command = new OleDbCommand("SELECT * FROM [TUTOR] WHERE 1=0", db))
                    using (var reader = command.ExecuteReader(CommandBehavior.SchemaOnly))
                    {
                        tutorIdAutoGenerated = false;
                        foreach (DataRow row in reader.GetSchemaTable().Rows)
                        {
                            if (Convert.ToString(row["ColumnName"]).Equals(
                                idColumn, StringComparison.OrdinalIgnoreCase))
                            {
                                tutorIdAutoGenerated = row.Table.Columns.Contains("IsAutoIncrement") &&
                                    row["IsAutoIncrement"] != DBNull.Value &&
                                    Convert.ToBoolean(row["IsAutoIncrement"]);
                                break;
                            }
                        }
                    }
                }
                updatingSelection = true;
                gridTutors.DataSource = table;
                gridTutors.AutoGenerateColumns = true;
                gridTutors.AutoSizeColumnsMode = DataGridViewAutoSizeColumnsMode.Fill;
                gridTutors.Columns[idColumn].HeaderText = "Tutor ID";
                gridTutors.Columns[idColumn].FillWeight = 48;
                gridTutors.Columns["FirstName"].HeaderText = "First name";
                gridTutors.Columns["LastName"].HeaderText = "Last name";
                gridTutors.Columns["Email"].HeaderText = "Email address";
                gridTutors.Columns["Email"].FillWeight = 190;
                if (gridTutors.Columns.Contains("SubjectSpecialty"))
                    gridTutors.Columns["SubjectSpecialty"].Visible = false;
                if (activeColumn != null) gridTutors.Columns[activeColumn].Visible = false;
                gridTutors.ClearSelection();
                updatingSelection = false;
                ClearEditor();
                ApplySearch();
                lblTutorCount.Text = table.Rows.Count + " tutors";
                lblMessage.Text = "Select a tutor to edit, or choose New Tutor.";
            }
            catch (Exception ex)
            {
                lblMessage.Text = "Could not load tutor records.";
                MessageBox.Show("Could not load tutors: " + ex.Message,
                    "Database error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void LoadCourses()
        {
            try
            {
                DataTable table = ReadTable("COURSE");
                string id = Column(table, "CourseID");
                if (id == null) throw new InvalidOperationException("Missing CourseID.");
                table.Columns.Add("Display", typeof(string));
                foreach (DataRow row in table.Rows)
                    row["Display"] = Convert.ToString(row["CourseCode"]) + " - " +
                                     Convert.ToString(row["CourseName"]);
                cmbCourse.DisplayMember = "Display";
                cmbCourse.ValueMember = id;
                cmbCourse.DataSource = table;
                cmbCourse.SelectedIndex = -1;
            }
            catch (Exception ex) { lblMessage.Text = "Courses unavailable: " + ex.Message; }
        }

        private void ApplySearch()
        {
            var table = gridTutors.DataSource as DataTable;
            if (table == null) return;
            var query = txtSearch.Text.Trim().Replace("'", "''").Replace("[", "[[]")
                .Replace("%", "[%]").Replace("*", "[*]");
            table.DefaultView.RowFilter = query.Length == 0 ? "" :
                "[FirstName] LIKE '%" + query + "%' OR [LastName] LIKE '%" + query +
                "%' OR [Email] LIKE '%" + query + "%'";
            lblTutorCount.Text = table.DefaultView.Count + " tutors";
            gridTutors.ClearSelection();
        }

        private void ShowSelected()
        {
            if (updatingSelection || gridTutors.SelectedRows.Count != 1 || idColumn == null)
                return;
            try
            {
                DataGridViewRow row = gridTutors.SelectedRows[0];
                if (row.Cells[idColumn].Value == DBNull.Value) return;
                selectedId = Convert.ToInt32(row.Cells[idColumn].Value);
                txtFirstName.Text = Convert.ToString(row.Cells["FirstName"].Value);
                txtLastName.Text = Convert.ToString(row.Cells["LastName"].Value);
                txtEmail.Text = Convert.ToString(row.Cells["Email"].Value);
                lblEditorHeading.Text = "Edit tutor #" + selectedId;
                btnSave.Text = "Save changes";
                lblMessage.Text = "Editing tutor #" + selectedId;
                btnAssignCourse.Enabled = true;
                btnAvailability.Enabled = true;
                btnRemoveTutor.Enabled = true;
                RefreshTutorLoginState();
                LoadTutorCourses();
            }
            catch (Exception ex) { lblMessage.Text = "Could not select tutor: " + ex.Message; }
        }

        private void NewTutor()
        {
            gridTutors.ClearSelection();
            ClearEditor();
            txtFirstName.Focus();
        }

        private void ClearEditor()
        {
            selectedId = 0;
            txtFirstName.Clear();
            txtLastName.Clear();
            txtEmail.Clear();
            lblEditorHeading.Text = "New tutor";
            btnSave.Text = "Save tutor";
            lblAssignedCourses.Text = "Save this tutor before assigning a course.";
            btnAssignCourse.Enabled = false;
            btnAvailability.Enabled = false;
            btnRemoveTutor.Enabled = false;
            btnCreateTutorLogin.Enabled = false;
            btnResetTutorLogin.Enabled = false;
            cmbCourse.SelectedIndex = -1;
        }

        private void LoadTutorCourses()
        {
            if (selectedId <= 0) return;
            try
            {
                int count = 0;
                using (var db = new OleDbConnection(connectionString))
                using (var cmd = new OleDbCommand(
                    "SELECT COUNT(*) FROM [TUTOR_COURSE] WHERE [TutorID]=?", db))
                {
                    cmd.Parameters.Add("@TutorID", OleDbType.Integer).Value = selectedId;
                    db.Open();
                    count = Convert.ToInt32(cmd.ExecuteScalar());
                }
                lblAssignedCourses.Text = count + " assigned course(s).";
            }
            catch (Exception ex) { lblAssignedCourses.Text = "Course lookup failed: " + ex.Message; }
        }

        private bool ValidateTutor(out string first, out string last, out string email)
        {
            first = txtFirstName.Text.Trim();
            last = txtLastName.Text.Trim();
            email = txtEmail.Text.Trim();
            if (first.Length == 0 || last.Length == 0 || email.Length == 0)
            {
                MessageBox.Show("First name, last name and email are all required.");
                return false;
            }
            if (first.Length > 100 || last.Length > 100 || email.Length > 255)
            {
                MessageBox.Show("A name or email exceeds the permitted length.");
                return false;
            }
            try
            {
                var address = new MailAddress(email);
                if (!address.Address.Equals(email, StringComparison.OrdinalIgnoreCase))
                    throw new FormatException();
            }
            catch
            {
                MessageBox.Show("Enter a valid tutor email address."); return false;
            }
            return true;
        }

        private void RemoveTutor()
        {
            if (selectedId <= 0)
            {
                MessageBox.Show("Select an existing tutor first.", "Remove tutor",
                    MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }

            int tutorId = selectedId;
            string tutorName = (txtFirstName.Text.Trim() + " " + txtLastName.Text.Trim()).Trim();
            if (MessageBox.Show("Permanently remove " + tutorName + " (Tutor #" +
                tutorId + ")? Their course assignments, availability, and sign-in will also be removed. " +
                "Tutors who have any session history cannot be removed.",
                "Confirm tutor removal", MessageBoxButtons.YesNo,
                MessageBoxIcon.Warning) != DialogResult.Yes)
                return;

            btnRemoveTutor.Enabled = false;
            try
            {
                using (var db = new OleDbConnection(connectionString))
                {
                    db.Open();
                    bool hasLoginTable = false;
                    DataTable schema = db.GetSchema("Tables");
                    foreach (DataRow table in schema.Rows)
                        if (Convert.ToString(table["TABLE_NAME"]).Equals(
                            "TUTOR_LOGIN", StringComparison.OrdinalIgnoreCase))
                        {
                            hasLoginTable = true;
                            break;
                        }

                    using (var transaction = db.BeginTransaction())
                    {
                        try
                        {
                            using (var check = new OleDbCommand(
                                "SELECT COUNT(*) FROM [TUTORING_SESSION] WHERE [TutorID]=?",
                                db, transaction))
                            {
                                check.Parameters.Add("@TutorID", OleDbType.Integer).Value = tutorId;
                                if (Convert.ToInt32(check.ExecuteScalar()) > 0)
                                    throw new InvalidOperationException(
                                        "This tutor has recorded or scheduled tutoring sessions. " +
                                        "Removing them would damage session history and reports. " +
                                        "Keep the tutor record instead.");
                            }

                            string[] linkedTables = hasLoginTable
                                ? new[] { "TUTOR_LOGIN", "TUTOR_AVAILABILITY", "TUTOR_COURSE" }
                                : new[] { "TUTOR_AVAILABILITY", "TUTOR_COURSE" };
                            foreach (string table in linkedTables)
                            {
                                using (var command = new OleDbCommand(
                                    "DELETE FROM [" + table + "] WHERE [TutorID]=?",
                                    db, transaction))
                                {
                                    command.Parameters.Add("@TutorID", OleDbType.Integer).Value = tutorId;
                                    command.ExecuteNonQuery();
                                }
                            }

                            using (var command = new OleDbCommand(
                                "DELETE FROM [TUTOR] WHERE [" + idColumn + "]=?",
                                db, transaction))
                            {
                                command.Parameters.Add("@TutorID", OleDbType.Integer).Value = tutorId;
                                if (command.ExecuteNonQuery() != 1)
                                    throw new InvalidOperationException(
                                        "The selected tutor no longer exists. Nothing was removed.");
                            }
                            transaction.Commit();
                        }
                        catch
                        {
                            transaction.Rollback();
                            throw;
                        }
                    }
                }

                LoadTutors();
                lblMessage.Text = "Tutor #" + tutorId + " removed from the database.";
                MessageBox.Show("Tutor and related sign-in, course and availability records " +
                    "were removed successfully.", "Tutor removed",
                    MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            catch (Exception ex)
            {
                lblMessage.Text = "Tutor removal did not complete.";
                MessageBox.Show("Tutor could not be removed. No partial removal was saved.\n\n" +
                    ex.Message, "Remove tutor", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
            finally
            {
                btnRemoveTutor.Enabled = selectedId > 0;
            }
        }

        private void SaveTutor()
        {
            string first, last, email;
            if (!ValidateTutor(out first, out last, out email)) return;
            try
            {
                int savedId = selectedId;
                using (var db = new OleDbConnection(connectionString))
                {
                    db.Open();
                    using (var transaction = db.BeginTransaction())
                    {
                        try
                        {
                            string tutorId = BookingData.GetColumn(db, transaction, "TUTOR", "TutorID");
                            using (var dup = new OleDbCommand(
                                "SELECT COUNT(*) FROM [TUTOR] WHERE LCase([Email])=? AND [" +
                                tutorId + "]<>?", db, transaction))
                            {
                                dup.Parameters.Add("@Email", OleDbType.VarWChar).Value = email.ToLowerInvariant();
                                dup.Parameters.Add("@TutorID", OleDbType.Integer).Value = selectedId;
                                if (Convert.ToInt32(dup.ExecuteScalar()) > 0)
                                {
                                    MessageBox.Show("A tutor with this email already exists.");
                                    return;
                                }
                            }
                            if (selectedId == 0)
                            {
                                string query = tutorIdAutoGenerated
                                    ? "INSERT INTO [TUTOR] ([FirstName],[LastName],[Email]) VALUES (?,?,?)"
                                    : "INSERT INTO [TUTOR] ([" + tutorId +
                                      "],[FirstName],[LastName],[Email]) VALUES (?,?,?,?)";
                                using (var cmd = new OleDbCommand(query, db, transaction))
                                {
                                    if (!tutorIdAutoGenerated)
                                    {
                                        using (var max = new OleDbCommand(
                                            "SELECT MAX([" + tutorId + "]) FROM [TUTOR]", db, transaction))
                                        {
                                            object value = max.ExecuteScalar();
                                            savedId = value == null || value == DBNull.Value
                                                ? 1 : checked(Convert.ToInt32(value) + 1);
                                        }
                                        cmd.Parameters.Add("@ID", OleDbType.Integer).Value = savedId;
                                    }
                                    cmd.Parameters.Add("@FirstName", OleDbType.VarWChar).Value = first;
                                    cmd.Parameters.Add("@LastName", OleDbType.VarWChar).Value = last;
                                    cmd.Parameters.Add("@Email", OleDbType.VarWChar).Value = email;
                                    if (cmd.ExecuteNonQuery() != 1)
                                        throw new InvalidOperationException("Insert did not create a tutor.");
                                }
                                if (tutorIdAutoGenerated)
                                {
                                    using (var identity = new OleDbCommand("SELECT @@IDENTITY", db, transaction))
                                        savedId = Convert.ToInt32(identity.ExecuteScalar());
                                }
                            }
                            else
                            {
                                using (var cmd = new OleDbCommand(
                                    "UPDATE [TUTOR] SET [FirstName]=?, [LastName]=?, [Email]=? WHERE [" +
                                    tutorId + "]=?", db, transaction))
                                {
                                    cmd.Parameters.Add("@FirstName", OleDbType.VarWChar).Value = first;
                                    cmd.Parameters.Add("@LastName", OleDbType.VarWChar).Value = last;
                                    cmd.Parameters.Add("@Email", OleDbType.VarWChar).Value = email;
                                    cmd.Parameters.Add("@TutorID", OleDbType.Integer).Value = selectedId;
                                    if (cmd.ExecuteNonQuery() != 1)
                                        throw new InvalidOperationException("No existing tutor record was updated.");
                                }
                            }
                            transaction.Commit();
                        }
                        catch { transaction.Rollback(); throw; }
                    }
                }
                // A successful database write is always followed by a fresh read.
                LoadTutors();
                foreach (DataGridViewRow row in gridTutors.Rows)
                    if (row.Cells[idColumn].Value != DBNull.Value &&
                        Convert.ToInt32(row.Cells[idColumn].Value) == savedId)
                    { row.Selected = true; break; }
                lblMessage.Text = "Tutor #" + savedId + " saved to the project database.";
                MessageBox.Show("Tutor saved successfully to the Access database.",
                    "EduConnect", MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            catch (OleDbException ex)
            {
                MessageBox.Show("Access could not save the tutor. Close the database table in Access " +
                    "and check its key constraints.\n\n" + ex.Message,
                    "Database error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
            catch (Exception ex)
            {
                MessageBox.Show("Tutor not saved.\n\n" + ex.Message,
                    "Save error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void RefreshTutorLoginState()
        {
            btnCreateTutorLogin.Enabled = false;
            btnResetTutorLogin.Enabled = false;
            if (selectedId <= 0) return;
            try
            {
                bool hasAccount;
                using (var db = new OleDbConnection(connectionString))
                {
                    db.Open();
                    hasAccount = TutorAuthentication.HasAccount(db, selectedId);
                }
                btnCreateTutorLogin.Enabled = !hasAccount;
                btnResetTutorLogin.Enabled = hasAccount;
            }
            catch (Exception ex)
            {
                lblMessage.Text = "Cannot check tutor login: " + ex.Message;
            }
        }

        private void ResetTutorLogin()
        {
            if (selectedId <= 0)
            {
                MessageBox.Show("Select an existing tutor first."); return;
            }
            if (MessageBox.Show(
                "Reset the password for Tutor #" + selectedId + "? " +
                "Their previous password will immediately stop working.",
                "Reset tutor password", MessageBoxButtons.YesNo,
                MessageBoxIcon.Warning) != DialogResult.Yes)
                return;

            try
            {
                string temporaryPassword;
                using (var db = new OleDbConnection(connectionString))
                {
                    db.Open();
                    temporaryPassword = TutorAuthentication.ResetPassword(db, selectedId);
                }
                MessageBox.Show("Tutor ID: " + selectedId +
                    "\nNew temporary password: " + temporaryPassword +
                    "\n\nShare this only with the tutor. The previous password " +
                    "is now invalid. The new password will not be shown again.",
                    "Tutor password reset", MessageBoxButtons.OK,
                    MessageBoxIcon.Information);
                lblMessage.Text = "Password reset for tutor #" + selectedId + ".";
                RefreshTutorLoginState();
            }
            catch (Exception ex)
            {
                MessageBox.Show("Password reset failed.\n\n" + ex.Message,
                    "Tutor account", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void CreateTutorLogin()
        {
            if (selectedId <= 0)
            {
                MessageBox.Show("Save or select a tutor before creating an account.");
                return;
            }
            if (MessageBox.Show(
                "Create a tutor sign-in account for Tutor #" + selectedId + "? " +
                "A temporary password will be shown once. Hand it directly to the tutor.",
                "Tutor account", MessageBoxButtons.YesNo,
                MessageBoxIcon.Question) != DialogResult.Yes)
                return;

            try
            {
                string temporaryPassword;
                using (var db = new OleDbConnection(connectionString))
                {
                    db.Open();
                    temporaryPassword = TutorAuthentication.Provision(db, selectedId);
                }

                MessageBox.Show("Tutor ID: " + selectedId + "\nTemporary password: " +
                    temporaryPassword + "\n\nShare this password privately with the tutor. " +
                    "It will not be shown again.",
                    "New tutor sign-in", MessageBoxButtons.OK,
                    MessageBoxIcon.Information);
                lblMessage.Text = "Tutor #" + selectedId + " now has a sign-in account.";
                RefreshTutorLoginState();
            }
            catch (Exception ex)
            {
                MessageBox.Show("Tutor account could not be created.\n\n" + ex.Message,
                    "Tutor account error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void OpenAvailability()
        {
            if (selectedId <= 0)
            {
                MessageBox.Show("Save or select a tutor before changing availability.");
                return;
            }
            string name = (txtFirstName.Text.Trim() + " " + txtLastName.Text.Trim()).Trim();
            using (var form = new TutorAvailability(selectedId, name))
                form.ShowDialog(this);
        }

        private void AssignCourse()
        {
            if (selectedId <= 0) { MessageBox.Show("Save or select a tutor first."); return; }
            if (cmbCourse.SelectedValue == null || cmbCourse.SelectedValue is DataRowView)
            { MessageBox.Show("Select a valid course."); return; }
            int courseId = Convert.ToInt32(cmbCourse.SelectedValue);
            try
            {
                using (var db = new OleDbConnection(connectionString))
                {
                    db.Open();
                    using (var exists = new OleDbCommand(
                        "SELECT COUNT(*) FROM [TUTOR_COURSE] WHERE [TutorID]=? AND [CourseID]=?", db))
                    {
                        exists.Parameters.Add("@TutorID", OleDbType.Integer).Value = selectedId;
                        exists.Parameters.Add("@CourseID", OleDbType.Integer).Value = courseId;
                        if (Convert.ToInt32(exists.ExecuteScalar()) != 0)
                        { MessageBox.Show("This course is already assigned to the tutor."); return; }
                    }
                    using (var cmd = new OleDbCommand(
                        "INSERT INTO [TUTOR_COURSE] ([TutorID],[CourseID]) VALUES (?,?)", db))
                    {
                        cmd.Parameters.Add("@TutorID", OleDbType.Integer).Value = selectedId;
                        cmd.Parameters.Add("@CourseID", OleDbType.Integer).Value = courseId;
                        if (cmd.ExecuteNonQuery() != 1)
                            throw new InvalidOperationException("Course assignment failed.");
                    }
                }
                LoadTutorCourses();
                lblMessage.Text = "Course assigned to tutor #" + selectedId + ".";
            }
            catch (Exception ex)
            {
                MessageBox.Show("Course assignment not saved.\n\n" + ex.Message,
                    "Database error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }
    }
